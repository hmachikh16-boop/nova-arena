function mirrorRect(rect) {
  return {
    x: WORLD.width - rect.x - rect.w,
    y: WORLD.height - rect.y - rect.h,
    w: rect.w,
    h: rect.h,
  };
}

function symmetricRects(base) {
  return Object.freeze([
    ...base.map((rect) => Object.freeze({ ...rect })),
    ...base.map((rect) => Object.freeze(mirrorRect(rect))),
  ]);
}

